BEGIN;
CREATE TABLE book_copies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shop_id BIGINT NOT NULL REFERENCES shops(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 code VARCHAR(39) NOT NULL UNIQUE,
 book_condition VARCHAR(20) NOT NULL CHECK(book_condition IN ('UNCLASSIFIED','LIKE_NEW','GOOD','ACCEPTABLE')),
 defects VARCHAR(2000) NOT NULL DEFAULT '',
 price NUMERIC(12,2) NOT NULL CHECK(price >= 0),
 status VARCHAR(20) NOT NULL CHECK(status IN ('AVAILABLE','UNAVAILABLE','RESERVED','SOLD')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version INTEGER NOT NULL DEFAULT 0,
 CHECK(status <> 'AVAILABLE' OR book_condition <> 'UNCLASSIFIED')
);
CREATE INDEX book_copies_shop ON book_copies(shop_id,created_at DESC,id DESC);
CREATE INDEX book_copies_product_status ON book_copies(product_id,status,shop_id);
CREATE TABLE inventory_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 copy_id BIGINT NOT NULL REFERENCES book_copies(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(20) NOT NULL,
 old_status VARCHAR(20), new_status VARCHAR(20) NOT NULL,
 old_condition VARCHAR(20), new_condition VARCHAR(20) NOT NULL,
 old_price NUMERIC(12,2), new_price NUMERIC(12,2) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX inventory_movements_copy ON inventory_movements(copy_id,created_at DESC,id DESC);
COMMIT;
