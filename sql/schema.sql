-- REVIEW AND EXECUTE MANUALLY ONLY, in a dedicated empty database.
-- Application/tests never execute this file. PostgreSQL 17.
BEGIN;
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(50) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('ADMIN','USER')),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 blocked BOOLEAN NOT NULL DEFAULT FALSE,
 auth_version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 image VARCHAR(1000) NOT NULL DEFAULT '',
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE remember_tokens (
 token_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX remember_tokens_user ON remember_tokens(user_id);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 title VARCHAR(200) NOT NULL,
 author VARCHAR(150) NOT NULL,
 description VARCHAR(10000) NOT NULL DEFAULT '',
 image VARCHAR(1000) NOT NULL DEFAULT '',
 isbn VARCHAR(20),
 publisher VARCHAR(200),
 published_year INTEGER,
 language VARCHAR(50),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX products_newest ON products(created_at DESC,id DESC);
CREATE INDEX products_category ON products(category_id);
CREATE TABLE otp_challenges (
 id VARCHAR(36) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 purpose VARCHAR(20) NOT NULL CHECK(purpose IN ('ACTIVATE','RESET')),
 otp_hash VARCHAR(64) NOT NULL,
 sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 5),
 consumed BOOLEAN NOT NULL DEFAULT FALSE,
 delivered BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(user_id,purpose)
);
CREATE TABLE shops (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES users(id),
 name VARCHAR(150) NOT NULL,
 address VARCHAR(300) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','SUSPENDED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE shop_applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 applicant_id BIGINT NOT NULL REFERENCES users(id),
 shop_id BIGINT UNIQUE REFERENCES shops(id),
 name VARCHAR(150) NOT NULL,
 address VARCHAR(300) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 review_note VARCHAR(500) NOT NULL DEFAULT '',
 reviewed_by BIGINT REFERENCES users(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reviewed_at TIMESTAMP WITH TIME ZONE,
 CHECK ((status='PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL AND shop_id IS NULL)
 OR (status='APPROVED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND shop_id IS NOT NULL)
 OR (status='REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND shop_id IS NULL))
);
CREATE UNIQUE INDEX shop_applications_one_pending ON shop_applications(applicant_id) WHERE status='PENDING';
CREATE INDEX shop_applications_history ON shop_applications(applicant_id,id DESC);
CREATE TABLE shop_memberships (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shop_id BIGINT NOT NULL REFERENCES shops(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 role VARCHAR(20) NOT NULL CHECK(role IN ('SELLER','MANAGER')),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(shop_id,user_id)
);
CREATE INDEX shop_memberships_user ON shop_memberships(user_id,active);
CREATE TABLE shop_audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shop_id BIGINT REFERENCES shops(id),
 application_id BIGINT REFERENCES shop_applications(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(40) NOT NULL,
 note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX shop_audit_shop_time ON shop_audit_events(shop_id,created_at DESC,id DESC);
CREATE TABLE book_copies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shop_id BIGINT NOT NULL REFERENCES shops(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 code VARCHAR(39) NOT NULL UNIQUE,
 book_condition VARCHAR(20) NOT NULL CHECK(book_condition IN ('UNCLASSIFIED','LIKE_NEW','GOOD','ACCEPTABLE')),
 defects VARCHAR(2000) NOT NULL DEFAULT '',
 price NUMERIC(12,2) NOT NULL CHECK(price >= 0),
 status VARCHAR(20) NOT NULL CHECK(status IN ('AVAILABLE','UNAVAILABLE','RESERVED','SOLD')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version INTEGER NOT NULL DEFAULT 0,
 CHECK(status <> 'AVAILABLE' OR book_condition <> 'UNCLASSIFIED')
);
CREATE INDEX book_copies_shop ON book_copies(shop_id,created_at DESC,id DESC);
CREATE INDEX book_copies_product_status ON book_copies(product_id,status,shop_id);
CREATE TABLE inventory_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 copy_id BIGINT NOT NULL REFERENCES book_copies(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(20) NOT NULL,
 old_status VARCHAR(20), new_status VARCHAR(20) NOT NULL,
 old_condition VARCHAR(20), new_condition VARCHAR(20) NOT NULL,
 old_price NUMERIC(12,2), new_price NUMERIC(12,2) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX inventory_movements_copy ON inventory_movements(copy_id,created_at DESC,id DESC);
CREATE TABLE media_assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id VARCHAR(500) NOT NULL UNIQUE,
 resource_type VARCHAR(20) NOT NULL CHECK(resource_type IN ('image','video','raw')),
 secure_url VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','REPLACED','DELETED')),
 owner_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
 shop_id BIGINT REFERENCES shops(id) ON DELETE SET NULL,
 product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
 bytes BIGINT NOT NULL CHECK(bytes >= 0),
 width INTEGER,
 height INTEGER,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX media_assets_owner ON media_assets(owner_id,status);
CREATE INDEX media_assets_product ON media_assets(product_id,status);
CREATE TABLE customer_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 display_name VARCHAR(120) NOT NULL DEFAULT '',
 phone VARCHAR(30) NOT NULL DEFAULT '',
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE addresses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 label VARCHAR(60) NOT NULL,
 recipient_name VARCHAR(120) NOT NULL,
 phone VARCHAR(30) NOT NULL,
 line1 VARCHAR(250) NOT NULL,
 ward VARCHAR(100) NOT NULL DEFAULT '',
 district VARCHAR(100) NOT NULL DEFAULT '',
 city VARCHAR(100) NOT NULL,
 is_default BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX addresses_user ON addresses(user_id,is_default DESC,id);
CREATE TABLE favorites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id,product_id)
);
CREATE INDEX favorites_user ON favorites(user_id,created_at DESC,id DESC);
CREATE TABLE recently_viewed (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
 viewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id,product_id)
);
CREATE INDEX recently_viewed_user ON recently_viewed(user_id,viewed_at DESC,id DESC);
CREATE TABLE carts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE cart_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cart_id BIGINT NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
 copy_id BIGINT NOT NULL REFERENCES book_copies(id) ON DELETE RESTRICT,
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price >= 0),
 added_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(cart_id,copy_id)
);
CREATE INDEX cart_items_cart ON cart_items(cart_id,id);
CREATE TABLE checkout_groups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 idempotency_key VARCHAR(80) NOT NULL,
 address_snapshot VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','CONFIRMED','CANCELLED','COMPLETED')),
 shipping_fee NUMERIC(12,2) NOT NULL CHECK(shipping_fee >= 0),
 total NUMERIC(12,2) NOT NULL CHECK(total >= 0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id,idempotency_key)
);
CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 checkout_group_id BIGINT NOT NULL REFERENCES checkout_groups(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 shop_id BIGINT NOT NULL REFERENCES shops(id),
 idempotency_key VARCHAR(80) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','CONFIRMED','SHIPPING','CANCELLED','COMPLETED')),
 shop_name_snapshot VARCHAR(150) NOT NULL,
 recipient_name VARCHAR(120) NOT NULL,
 phone VARCHAR(30) NOT NULL,
 address_snapshot VARCHAR(500) NOT NULL,
 subtotal NUMERIC(12,2) NOT NULL CHECK(subtotal >= 0),
 shipping_fee NUMERIC(12,2) NOT NULL CHECK(shipping_fee >= 0),
 total NUMERIC(12,2) NOT NULL CHECK(total = subtotal + shipping_fee),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 -- One checkout key may create one child order per shop.
 UNIQUE(user_id,idempotency_key,shop_id)
);
CREATE INDEX orders_user_time ON orders(user_id,created_at DESC,id DESC);
CREATE INDEX orders_shop_time ON orders(shop_id,created_at DESC,id DESC);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
 copy_id BIGINT NOT NULL REFERENCES book_copies(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 title_snapshot VARCHAR(200) NOT NULL,
 cover_url_snapshot VARCHAR(1000) NOT NULL DEFAULT '',
 condition_snapshot VARCHAR(20) NOT NULL,
 copy_code_snapshot VARCHAR(80) NOT NULL,
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price >= 0),
 UNIQUE(order_id,copy_id)
);
CREATE TABLE order_status_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
 status VARCHAR(20) NOT NULL,
 note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX order_status_history_order ON order_status_history(order_id,created_at DESC,id DESC);
CREATE TABLE inventory_reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
 copy_id BIGINT NOT NULL REFERENCES book_copies(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','RELEASED','COMMITTED')),
 -- COD reservations remain active until the order is cancelled or completed.
 expires_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX inventory_reservations_active ON inventory_reservations(copy_id) WHERE status='ACTIVE';
CREATE INDEX inventory_reservations_expiry ON inventory_reservations(status,expires_at);
CREATE TABLE reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
 order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
 rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
 body VARCHAR(5000) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PUBLISHED','HIDDEN')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(user_id,product_id)
);
CREATE INDEX reviews_product ON reviews(product_id,status,created_at DESC,id DESC);
COMMIT;
